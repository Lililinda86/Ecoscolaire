import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';

// Metadata and short existing assessments only; never copies ministry PDFs.
const root = 'docs/pedagogy-content-completion/';
const audit = JSON.parse(readFileSync(root + 'OWNER_CURRICULUM_PROPOSALS.audit.json', 'utf8'));
const markdown = readFileSync(root + 'OWNER_CURRICULUM_PROPOSALS.md', 'utf8');
const levels = [
  ...['sil','cp','ce1','ce2','cm1','cm2'].map(x => 'fr-primary-' + x),
  ...[1,2,3,4,5,6].map(x => 'en-primary-' + x),
  ...['ms','gs','ps','pre'].map(x => 'fr-preschool-' + x),
  ...[2,3,1,'pre'].map(x => 'en-nursery-' + x),
  ...['6e','5e','4e','3e','2nde','terminale','1re'].map(x => 'fr-secondary-' + x),
  ...['form1','form2','form3','form4','form5','lower-sixth','upper-sixth'].map(x => 'en-secondary-' + x),
];
const hash = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
const proposals = audit.classes.map((item, i) => {
  const card = markdown.split('### ' + item.id + ' — ')[1]?.split(/\n### /)[0];
  assert(card, item.id);
  const field = label => {
    const found = card.split(label + ': ')[1]?.split('\n')[0]?.trim();
    assert(found, item.id + ': ' + label); return found;
  };
  const sources = [...card.matchAll(/- DOCUMENT: \[([^\]]+)\]\((https:\/\/[^)]+)\) ; VERSION\/DATE: ([^\n]+)/g)].map(match => ({ title: match[1], url: match[2], detail: match[3].trim() }));
  const highConfidence = i < 12;
  const local = item.recommendation === 'PROGRAMME ITALO LOCAL À VALIDER';
  const base = {
    id: item.id, catalogLevelId: levels[i], group: item.group.slice(3), name: item.name,
    section: field('SECTION'), subsystem: field('SOUS-SYSTÈME'), localLevel: field('NIVEAU LOCAL'),
    program: item.proposal, authority: field('AUTORITÉ'), sources,
    authentication: 'Provenance ministérielle documentée pour les liens présents ; promulgation et applicabilité actuelle non certifiées. Voir les réserves de chaque document.',
    covered: field('MATIÈRES/DOMAINES OFFICIELS RETROUVÉS'), missing: item.missing,
    certain: field('CORRESPONDANCES CERTAINES'), uncertain: field('CORRESPONDANCES PROBABLES'),
    recommendation: highConfidence ? 'APPROUVER' : local || ['D13','D14','D17','D18'].includes(item.id) ? 'PROGRAMME ITALO LOCAL À VALIDER' : 'ATTENDRE SOURCE OFFICIELLE',
    rationale: field('JUSTIFICATION'), highConfidence,
    // Conditional preschool mappings have a document, but no established local equivalence.
    missingSource: !highConfidence && !['D13','D14','D17','D18'].includes(item.id),
    sourceVersion: hash(sources), sourceDate: audit.sourceDate,
  };
  return { ...base, mappingVersion: hash(base) };
});
assert.equal(proposals.length, 34);
assert.equal(proposals.filter(x => x.highConfidence).length, 12);
assert.equal(new Set(levels).size, 34);
const output = '// Generated by scripts/build-curriculum-review-manifest.mjs. No human decisions.\nexport const curriculumReviewProposals = ' + JSON.stringify(proposals, null, 2) + ';\n';
for (const file of ['src/features/pedagogy/resources/curriculumReviewManifest.ts', 'functions/src/pedagogy/curriculumReviewManifest.ts']) {
  if (process.argv.includes('--check')) assert.equal(readFileSync(file, 'utf8'), output, file + ' stale');
  else writeFileSync(file, output);
}
console.log('Curriculum manifest: 34 proposals, 12 high confidence, no decisions.');
